"""Constructive Layer-0 free-face variants and controlled collapsible horn chains.

All theorems and algorithms operate on general Boolean cubical complexes and
Layer-0 cyclic cores produced by exact logic minimization — never grid surrogates.

Suite of constructive theorems (paired with ``lean/TopoSpine/HornChains.lean``):

1. **Theorem H1 — Horn Retraction (``horn_replace_once``, ``horn_exact_iff_holds``)**:
   Removing the elementary simple-homotopy pair ``R_f = {f, f_top}`` replaces
   ``f_top`` in ``CC`` by its horn ``Λ_f(f_top) = ∂f_top \\ {f}``.
   - On any Layer-0 cyclic core (no essential columns), ``CC_horn`` covers 100% of
     residual ON-minterms ``R`` and induces ``H*(K; F2) ≅ H*(K \\ R_f; F2)``.
   - ``opt(CC_horn) == opt(CC)`` iff some minimum cover of ``CC`` excludes ``f_top``
     OR includes ``f_top`` while covering ``(f_top ∩ R) \\ h`` without ``f_top`` for
     at least one horn face ``h ∈ Λ_f(f_top)`` (strictly dominating single-face swap).

2. **Theorem H2 — Cylinder & Ambient Cone-Prism Expansion (``cylinder_product_cubes``,
   ``ambient_cone_prism_cubes``)**:
   - Global cross-product ``CC × I^m`` preserves primes, free faces, cohomology,
     and ``opt``.
   - Ambient cone-prism ``E(F) = (F × {0}) ∪ (Q_n × {1}) ⊆ Q_{n+1}`` expands every
     prime ``p ↦ p × -`` into a contractible complex with complement ``F^c × {0}``
     and exact roof offset ``opt(E(F)) = 1 + opt(F)`` whenever ``F ≠ Q_n``.

3. **Theorem H3 — Complement Boundary Free-Face Duality (``complement_cubes``,
   ``is_free_face_via_complement``, ``free_faces_via_complement``)**:
   For ``p ∈ P(F)`` and codimension-1 ``f < p``, ``f`` is a free face of ``p`` in
   ``C(F)`` iff every external normal reflection ``f|_{x_j := 1 - p_j}`` across fixed
   literals of ``p`` meets the complement ``F^c = Q_n \\ F``.  Decides free faces in
   ``<= n - dim(p)`` cofactor/complement queries without enumerating ``P(F)``.

4. **Theorem H4 — Controlled Collapsible Horn Chains (``collapse_to_topological_spine``,
   ``filtration_compatible_spine``, ``controlled_horn_chain_cover``)**:
   - Unfiltered horn chains preserve exact cubical cohomology ``H*(K; F2)``;
     filtration-compatible chains (``birth(f) == birth(f_top)``) preserve persistent
     cohomology Betti curves across all filtration grades.
   - Controlled covering modes: ``"exact"`` (100% optimal), ``"approx"`` (single
     chain to spine + blobs with window ``[L_MIS, U]``), and ``"probabilistic"``
     (``K`` soft-weighted randomized chains with ``(1 - q)^K`` tail decay and
     immediate optimality certification whenever ``U_best == L_MIS``).
"""

