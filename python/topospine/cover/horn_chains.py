# ----------------------------------------------------------------- exact cubical cohomology & persistence
def cubical_cohomology_betti_f2(cells: Sequence[Any]) -> list[int]:
    """Exact cubical cohomology Betti numbers ``[β^0, β^1, ..., β^D]`` over ``F2``
    for the face-closed cubical complex generated by ``cells`` (Boolean or Grid cubes).
    """
    if not cells:
        return []
    by_dim: dict[int, set[Any]] = {}
    visited: set[Any] = set()

    def add_closure(c: Any) -> None:
        if c in visited:
            return
        visited.add(c)
        by_dim.setdefault(c.dimension, set()).add(c)
        for f in c.faces():
            add_closure(f)

    for c in cells:
        add_closure(c)

    max_d = max(by_dim)
    graded = {d: sorted(by_dim.get(d, set()), key=str) for d in range(max_d + 1)}
    coboundary_rank: dict[int, int] = {}

    for d in range(max_d):
        dom = graded[d]
        cod = graded[d + 1]
        if not dom or not cod:
            coboundary_rank[d] = 0
            continue
        dom_idx = {c: j for j, c in enumerate(dom)}
        mat = [[0] * len(dom) for _ in cod]
        for i, tau in enumerate(cod):
            for f in tau.faces():
                j = dom_idx.get(f)
                if j is not None:
                    mat[i][j] ^= 1
        coboundary_rank[d] = _rank_f2(mat)

    betti: list[int] = []
    for d in range(max_d + 1):
        n_d = len(graded[d])
        r_out = coboundary_rank.get(d, 0)
        r_in = coboundary_rank.get(d - 1, 0) if d > 0 else 0
        betti.append(n_d - r_out - r_in)

    while len(betti) > 1 and betti[-1] == 0:
        betti.pop()
    return betti


def cubical_persistent_cohomology_betti_f2(
    cell_births: dict[BooleanCube, float],
    thresholds: Sequence[float],
) -> list[list[int]]:
    """Sublevel cubical cohomology Betti curves ``H*(K_{<= t}; F2)`` across ``thresholds``.

    Assumes ``cell_births`` is a valid monotone filtration on a face-closed cell set
    (``f <= τ  ==>  birth(f) <= birth(τ)``).
    """
    out: list[list[int]] = []
    for t in thresholds:
        sub_cells = [c for c, b in cell_births.items() if b <= t]
        out.append(cubical_cohomology_betti_f2(sub_cells))
    return out


# ----------------------------------------------------------------- Variant 1A: Horn replacement R_f = {f, f_top}
def horn_faces(f_top: Any, f: Any) -> list[Any]:
    """Return the horn ``Λ_f(f_top) = ∂f_top \\ {f}`` (all codimension-1 faces of ``f_top`` except ``f``).

    Works for both ``BooleanCube`` and ``GridCube`` (any object with ``faces()``).
    """
    all_f = list(f_top.faces())
    if f not in all_f:
        raise ValueError(f"{f} is not a codimension-1 face of {f_top}")
    return [g for g in all_f if g != f]


def horn_replace_once(
    cm: CoveringMatrix,
    col_j: int,
    f: BooleanCube,
) -> tuple[CoveringMatrix, str, list[str]]:
    """Remove ``f_top = cm.col_cubes[col_j]`` and insert active horn faces ``∂f_top \\ {f}``
    into ``cm`` (unit weight matching ``f_top``).

    Returns ``(cm_horn, p_name, inserted_horn_col_names)``.
    """
    if any(rc is None for rc in cm.row_cubes):
        raise ValueError("horn_replace_once requires typed row_cubes")
    f_top = cm.col_cubes[col_j]
    if not isinstance(f_top, BooleanCube):
        raise ValueError("horn_replace_once expects BooleanCube columns")

    sub = cm.copy()
    p_name = sub.cols[col_j]
    w = sub.weights[col_j]
    horn_names: list[str] = []

    for idx_h, h in enumerate(horn_faces(f_top, f)):
        cov = [rc.is_face_of(h) for rc in sub.row_cubes if rc is not None]  # type: ignore[attr-defined]
        if not any(cov):
            continue
        existing = next(
            (sub.cols[k] for k, c in enumerate(sub.col_cubes) if k != col_j and c == h),
            None,
        )
        if existing is not None:
            horn_names.append(existing)
        else:
            h_name = f"horn({p_name},{idx_h},{h})"
            sub.add_col(h_name, cov, weight=w, cube=h)
            horn_names.append(h_name)

    p_cur_idx = sub.cols.index(p_name)
    sub.remove_cols({p_cur_idx})
    return sub, p_name, horn_names


def decode_horn_cover(
    cm_orig: CoveringMatrix,
    cm_horn: CoveringMatrix,
    horn_cover_indices: Sequence[int],
    p_col_j: int,
    horn_col_names: Sequence[str],
) -> list[int]:
    """Decode a cover of ``cm_horn`` back to ``cm_orig``: replace any used horn face(s)
    with ``p_col_j``, then apply exact/greedy minimum sub-cover put-back (``Reduced``).
    """
    orig_masks, orig_univ = _masks_from_cm(cm_orig)
    orig_idx = {cm_orig.cols[k]: k for k in range(cm_orig.n_cols())}
    hset = set(horn_col_names)

    chosen_names = {cm_horn.cols[k] for k in horn_cover_indices}
    used_horn = bool(chosen_names & hset)
    kept_orig = [orig_idx[nm] for nm in sorted(chosen_names - hset) if nm in orig_idx]
    if used_horn:
        kept_orig.append(p_col_j)
    return _min_subcover_indices(orig_masks, kept_orig, orig_univ)


def horn_exact_iff_holds(
    cm: CoveringMatrix,
    col_j: int,
    f: BooleanCube,
) -> tuple[bool, int, int, int]:
    """Verify Theorem H1 on a Layer-0 unit-weight residual ``cm``:

    1. ``cm_horn`` is feasible on ``R``.
    2. ``opt(cm_horn) == opt(cm)`` iff ``C_out == opt(cm)`` OR there exists some horn
       face ``h ∈ ∂f_top \\ {f}`` such that ``(f_top ∩ R) \\ h`` is coverable by at most
       ``opt(cm) - 1`` columns of ``cm \\ {f_top}`` together with ``R \\ f_top``.

    Returns ``(iff_matches, opt_orig, opt_horn, decoded_cost)``.
    """
    masks, univ = _masks_from_cm(cm)
    C = len(masks)
    opt_sol, _ = _solve_unit_bitmask_bb(masks, univ)
    opt = len(opt_sol)

    f_top = cm.col_cubes[col_j]
    assert isinstance(f_top, BooleanCube)
    cm_horn, _, h_names = horn_replace_once(cm, col_j, f)
    h_masks_table, h_univ = _masks_from_cm(cm_horn)
    # Check full coverage feasibility of cm_horn
    tot = 0
    for m in h_masks_table:
        tot |= m
    if (tot & h_univ) != h_univ:
        return False, opt, 10**9, 10**9

    h_sol, _ = _solve_unit_bitmask_bb(h_masks_table, h_univ)
    opt_horn = len(h_sol)
    dec_idx = decode_horn_cover(cm, cm_horn, h_sol, col_j, h_names)
    dec_cost = len(dec_idx)

    others = [masks[k] for k in range(C) if k != col_j]
    if all(((univ >> r) & 1) == 0 or any((m >> r) & 1 for m in others) for r in range(cm.n_rows())):
        cout = len(_solve_unit_bitmask_bb(others, univ)[0])
    else:
        cout = 10**9

    predicted = cout == opt
    if not predicted:
        for h in horn_faces(f_top, f):
            hm = sum(
                (1 << i)
                for i, rc in enumerate(cm.row_cubes)
                if rc is not None and rc.is_face_of(h)
            )
            miss = masks[col_j] & ~hm
            if miss == 0:
                predicted = True
                break
            need = (univ & ~masks[col_j]) | miss
            if all(((need >> r) & 1) == 0 or any((m >> r) & 1 for m in others) for r in range(cm.n_rows())):
                cr = len(_solve_unit_bitmask_bb(others, need)[0])
                if cr <= opt - 1:
                    predicted = True
                    break

    return (predicted == (opt_horn == opt) and dec_cost <= opt_horn), opt, opt_horn, dec_cost


# ----------------------------------------------------------------- Variant 1B: Cylinder & Cone-Prism expansions
def cylinder_product_cubes(
    cubes: Sequence[BooleanCube | str],
    m: int = 1,
) -> list[BooleanCube]:
    """Global cross-product ``C × I^m``: append ``m`` free coordinates ``-`` to every cube."""
    if m < 0:
        raise ValueError("m must be >= 0")
    raw = coerce_cubes(cubes)
    suffix = (None,) * m
    return [BooleanCube(c.bits + suffix) for c in raw]


def ambient_cone_prism_cubes(cubes: Sequence[BooleanCube | str]) -> list[BooleanCube]:
    """Embed ``F = ⋃ C ⊆ Q_n`` into ``Q_{n+1}`` as the contractible cone-prism
    ``E(F) = (F × {0}) ∪ (Q_n × {1})``.

    Returns the generator array ``[c × {0} for c in C] + [Q_n × {1}]``; Blake expansion
    lifts each prime ``p ∈ P(F)`` to ``p × -`` alongside the roof cube ``---...-1``,
    isolating ``F^c × {0}`` as the exact complement in ``Q_{n+1}``.
    """
    raw = coerce_cubes(cubes)
    if not raw:
        return []
    n = len(raw[0].bits)
    base = [BooleanCube(c.bits + (0,)) for c in raw]
    roof = BooleanCube((None,) * n + (1,))
    return absorb_cubes(base + [roof])


# ----------------------------------------------------------------- Variant 1C: Complement boundary free-face duality
def complement_cubes(
    cubes: Sequence[BooleanCube | str],
    n_vars: int | None = None,
) -> list[BooleanCube]:
    """Compute a cube-array representation of the complement ``F^c = Q_n \\ ⋃ C``
    directly in cube space via ``Q_n # C`` (no minterm enumeration).
    """
    raw = coerce_cubes(cubes)
    if not raw:
        if n_vars is None:
            raise ValueError("n_vars required when cubes is empty")
        return [BooleanCube((None,) * n_vars)]
    n = len(raw[0].bits)
    ambient = BooleanCube((None,) * n)
    return cube_difference(ambient, raw)


def is_free_face_via_complement(
    prime_p: BooleanCube,
    face_f: BooleanCube,
    *,
    on_cubes: Sequence[BooleanCube | str] | None = None,
    off_cubes: Sequence[BooleanCube | str] | None = None,
) -> bool:
    """Theorem H3 (Complement Boundary Duality):

    Given a prime implicant ``prime_p ∈ P(F)`` and codimension-1 face ``face_f < prime_p``,
    decide whether ``face_f`` is a free face of ``prime_p`` in ``C(F)`` WITHOUT
    generating ``P(F)`` — by checking that every external normal reflection
    ``face_f|_{x_j := 1 - p_j}`` across fixed literals of ``prime_p`` meets ``F^c``.

    Accepts either ``on_cubes`` (covering ``F``) or ``off_cubes`` (covering ``F^c``).
    """
    if face_f not in list(prime_p.faces()):
        raise ValueError(f"{face_f} is not a codimension-1 face of {prime_p}")
    if on_cubes is None and off_cubes is None:
        raise ValueError("provide either on_cubes or off_cubes")

    on_c = coerce_cubes(on_cubes) if on_cubes is not None else None
    off_c = coerce_cubes(off_cubes) if off_cubes is not None else None

    for j, pb in enumerate(prime_p.bits):
        if pb is None:
            continue
        bits = list(face_f.bits)
        bits[j] = 1 - pb
        neighbor = BooleanCube(tuple(bits))
        if off_c is not None:
            meets_complement = any(cube_intersection(neighbor, d) is not None for d in off_c)
        else:
            assert on_c is not None
            meets_complement = not cube_contained_in_union(neighbor, on_c)
        if not meets_complement:
            return False
    return True


def free_faces_via_complement(
    prime_p: BooleanCube,
    *,
    on_cubes: Sequence[BooleanCube | str] | None = None,
    off_cubes: Sequence[BooleanCube | str] | None = None,
) -> list[BooleanCube]:
    """Return all free faces of ``prime_p`` in ``C(F)`` via Complement Boundary Duality."""
    if prime_p.dimension < 1:
        return []
    return [
        f
        for f in prime_p.faces()
        if is_free_face_via_complement(prime_p, f, on_cubes=on_cubes, off_cubes=off_cubes)
    ]


# ----------------------------------------------------------------- Variant 2: Collapsible chains & controlled solver
@dataclass
class CollapsibleChainTrace:
    steps: list[tuple[BooleanCube, BooleanCube]]
    spine_generators: list[BooleanCube]
    initial_cell_count: int
    spine_cell_count: int


def collapse_to_topological_spine(
    top_cubes: Sequence[BooleanCube | str],
) -> CollapsibleChainTrace:
    """Collapse maximal free-face horn chains ``R_f = {f, f_top}`` down to a non-collapsible
    topological spine ``K_spine`` with ``H*(K_spine; F2) ≅ H*(K; F2)``.
    """
    gens = absorb_cubes(coerce_cubes(top_cubes))

    def count_closure(cs: Sequence[BooleanCube]) -> int:
        s: set[BooleanCube] = set()

        def visit(c: BooleanCube) -> None:
            if c in s:
                return
            s.add(c)
            for f in c.faces():
                visit(f)

        for c in cs:
            visit(c)
        return len(s)

    init_cnt = count_closure(gens)
    steps: list[tuple[BooleanCube, BooleanCube]] = []

    while True:
        found: tuple[int, BooleanCube, BooleanCube] | None = None
        # Collapse highest-dimension cells first along deterministic chains
        order = sorted(range(len(gens)), key=lambda i: (-gens[i].dimension, str(gens[i])))
        for idx in order:
            g = gens[idx]
            if g.dimension < 1:
                continue
            others = [gens[k] for k in range(len(gens)) if k != idx]
            ffs = [f for f in g.faces() if all(not f.is_face_of(o) for o in others)]
            if ffs:
                found = (idx, g, ffs[0])
                break
        if found is None:
            break
        idx, g, f = found
        steps.append((f, g))
        others = [gens[k] for k in range(len(gens)) if k != idx]
        horn_add = [h for h in horn_faces(g, f) if all(not h.is_face_of(o) for o in others)]
        gens = absorb_cubes(others + horn_add)

    return CollapsibleChainTrace(
        steps=steps,
        spine_generators=gens,
        initial_cell_count=init_cnt,
        spine_cell_count=count_closure(gens),
    )


def filtration_compatible_spine(
    cell_births: dict[BooleanCube, float],
) -> tuple[dict[BooleanCube, float], list[tuple[BooleanCube, BooleanCube]]]:
    """Collapse maximal filtration-compatible chains (``birth(f) == birth(f_top)``) on a
    face-closed filtered cubical complex, preserving persistent cohomology identically.
    """
    rem = dict(cell_births)
    steps: list[tuple[BooleanCube, BooleanCube]] = []

    while True:
        found: tuple[BooleanCube, BooleanCube] | None = None
        for g in sorted(rem, key=lambda c: (-c.dimension, str(c))):
            if g.dimension < 1:
                continue
            if any(o != g and g.is_face_of(o) for o in rem):
                continue
            for f in g.faces():
                if f not in rem or rem[f] != rem[g]:
                    continue
                if any(o != g and o != f and f.is_face_of(o) for o in rem):
                    continue
                found = (f, g)
                break
            if found is not None:
                break
        if found is None:
            break
        f, g = found
        steps.append((f, g))
        del rem[f]
        del rem[g]

    return rem, steps


@dataclass
class ControlledChainCoverResult:
    mode: ChainMode
    cover_indices: list[int]
    cost: float
    lower_bound: int
    upper_bound: int
    certified_optimal: bool
    chains_run: int
    total_horn_steps: int
    n_blobs: int
    bb_nodes: int
    wall_time_s: float
    notes: list[str] = field(default_factory=list)


def _single_horn_chain_trial(
    cm: CoveringMatrix,
    rng: random.Random | None,
    *,
    greedy: bool,
) -> tuple[list[int], int, int]:
    """Run one collapsible horn chain -> blobs -> decode + put-back on ``cm``.

    Returns ``(decoded_cover_indices, horn_steps, n_blobs)``.
    """
    orig_masks, orig_univ = _masks_from_cm(cm)
    idx_by_name = {cm.cols[j]: j for j in range(cm.n_cols())}

    cur = cm.copy()
    root_of = {c: c for c in cur.cols}
    forced_roots: set[str] = set()
    horn_steps = 0

    for step in range(64):
        cur, _, ess = reduce_to_cyclic_core(cur)
        for e in ess:
            forced_roots.add(root_of[e])
        if cur.n_rows() == 0:
            break
        cur, zmap, nz = zero_loss_free_face_pushdown(cur)
        for k, v in zmap.items():
            root_of[k] = root_of.get(v, v)
        if nz > 0:
            horn_steps += nz
            continue

        coll = list_collapsible_primes(cur)
        if not coll:
            break
        pairs: list[tuple[int, BooleanCube, int]] = []
        for j, faces in coll:
            for f in faces:
                if isinstance(f, BooleanCube):
                    # Count residual rows on f: smaller |f ∩ R| => opp(f) in horn covers more of p!
                    f_rows = sum(
                        1
                        for r in range(cur.n_rows())
                        if cur.matrix[r][j] and cur.row_cubes[r] is not None and cur.row_cubes[r].is_face_of(f)
                    )
                    pairs.append((j, f, f_rows))
        if not pairs:
            break

        if greedy or rng is None:
            pairs.sort(key=lambda item: (item[2], -cur.col_cubes[item[0]].dimension, str(item[1])))  # type: ignore[union-attr]
            j, f, _ = pairs[0]
        else:
            weights = [1.0 / (1.0 + item[2]) ** 2 for item in pairs]
            j, f, _ = rng.choices(pairs, weights=weights, k=1)[0]

        old_name = cur.cols[j]
        root = root_of[old_name]
        p_cube = cur.col_cubes[j]
        assert isinstance(p_cube, BooleanCube)
        for h_idx, h in enumerate(horn_faces(p_cube, f)):
            cov = [rc is not None and rc.is_face_of(h) for rc in cur.row_cubes]
            if any(cov):
                hn = f"hc({step},{h_idx},{h})"
                root_of[hn] = root
                cur.add_col(hn, cov, weight=1.0, cube=h)
        cur.remove_cols({j})
        horn_steps += 1

    blobs = partition_into_blobs(cur)
    for blob in blobs:
        bmasks, buniv = _masks_from_cm(blob)
        bsol, _ = _solve_unit_bitmask_bb(bmasks, buniv)
        for k in bsol:
            forced_roots.add(root_of[blob.cols[k]])

    raw_idx = [idx_by_name[nm] for nm in sorted(forced_roots) if nm in idx_by_name]
    red_idx = _min_subcover_indices(orig_masks, raw_idx, orig_univ)
    return red_idx, horn_steps, max(1, len(blobs)) if cm.n_rows() > 0 else 0


def controlled_horn_chain_cover(
    cm: CoveringMatrix,
    *,
    mode: ChainMode = "exact",
    num_chains: int = 8,
    seed: int = 0,
) -> ControlledChainCoverResult:
    """Controlled collapsible horn-chain covering algorithm (Theorem H4).

    * ``mode="approx"``: single deterministic minimal-loss horn chain -> spine blobs ->
      decode + put-back; returns certified cost window ``[L_MIS, U]``.
    * ``mode="probabilistic"``: up to ``num_chains`` soft-weighted randomized horn chains
      (first chain deterministic greedy, remaining randomized), stopping early as soon as
      ``U_best == L_MIS`` proves exact optimality.
    * ``mode="exact"``: exact reductions + zero-loss free-face chains + blob partitioning,
      warm-started by a fast horn-chain primal bound on each blob and closed by MIS-pruned
      exact B&B whenever ``L_MIS < U``.
    """
    t0 = time.perf_counter()
    if any(abs(w - 1.0) > 1e-9 for w in cm.weights):
        raise ValueError("controlled_horn_chain_cover expects unit weights")
    if cm.n_rows() == 0:
        return ControlledChainCoverResult(mode, [], 0.0, 0, 0, True, 0, 0, 0, 0, 0.0)

    orig_masks, orig_univ = _masks_from_cm(cm)
    C, R = cm.n_cols(), cm.n_rows()
    row_cols = [sum((1 << j) for j in range(C) if (orig_masks[j] >> r) & 1) for r in range(R)]
    global_lb = _mis_lower_bound(row_cols, orig_univ)

    if mode == "approx":
        sol, hsteps, nblobs = _single_horn_chain_trial(cm, None, greedy=True)
        ub = len(sol)
        return ControlledChainCoverResult(
            mode="approx",
            cover_indices=sol,
            cost=float(ub),
            lower_bound=global_lb,
            upper_bound=ub,
            certified_optimal=(ub == global_lb),
            chains_run=1,
            total_horn_steps=hsteps,
            n_blobs=nblobs,
            bb_nodes=0,
            wall_time_s=time.perf_counter() - t0,
        )

    if mode == "probabilistic":
        rng = random.Random(seed)
        best_sol: list[int] = list(range(C))
        best_ub = C
        chains_run = 0
        tot_steps = 0
        last_blobs = 1
        for k in range(max(1, num_chains)):
            cand, hsteps, nblobs = _single_horn_chain_trial(cm, rng, greedy=(k == 0))
            chains_run += 1
            tot_steps += hsteps
            last_blobs = nblobs
            if len(cand) < best_ub:
                best_ub = len(cand)
                best_sol = cand
            if best_ub <= global_lb:
                break
        return ControlledChainCoverResult(
            mode="probabilistic",
            cover_indices=best_sol,
            cost=float(best_ub),
            lower_bound=global_lb,
            upper_bound=best_ub,
            certified_optimal=(best_ub == global_lb),
            chains_run=chains_run,
            total_horn_steps=tot_steps,
            n_blobs=last_blobs,
            bb_nodes=0,
            wall_time_s=time.perf_counter() - t0,
        )

    if mode == "exact":
        idx_by_name = {cm.cols[j]: j for j in range(C)}
        work = cm.copy()
        root_of = {c: c for c in work.cols}
        picked_roots: set[str] = set()
        tot_steps = 0

        while True:
            work, _, ess = reduce_to_cyclic_core(work)
            for e in ess:
                picked_roots.add(root_of[e])
            if work.n_rows() == 0:
                break
            work, zmap, nz = zero_loss_free_face_pushdown(work)
            for k, v in zmap.items():
                root_of[k] = root_of.get(v, v)
            tot_steps += nz
            if nz == 0:
                break

        blobs = partition_into_blobs(work)
        bb_nodes = 0
        chains_run = 0
        for blob in blobs:
            bm, bu = _masks_from_cm(blob)
            b_rc = [sum((1 << j) for j in range(blob.n_cols()) if (bm[j] >> r) & 1) for r in range(blob.n_rows())]
            b_lb = _mis_lower_bound(b_rc, bu)
            warm_sol, hsteps, _ = _single_horn_chain_trial(blob, None, greedy=True)
            chains_run += 1
            tot_steps += hsteps
            if len(warm_sol) == b_lb:
                for k in warm_sol:
                    picked_roots.add(root_of[blob.cols[k]])
                continue
            bsol, nodes = _solve_unit_bitmask_bb(bm, bu, initial_best=warm_sol)
            bb_nodes += nodes
            for k in bsol:
                picked_roots.add(root_of[blob.cols[k]])

        chosen = _min_subcover_indices(
            orig_masks,
            [idx_by_name[nm] for nm in sorted(picked_roots)],
            orig_univ,
        )
        opt_c = len(chosen)
        return ControlledChainCoverResult(
            mode="exact",
            cover_indices=chosen,
            cost=float(opt_c),
            lower_bound=opt_c,
            upper_bound=opt_c,
            certified_optimal=True,
            chains_run=chains_run,
            total_horn_steps=tot_steps,
            n_blobs=len(blobs),
            bb_nodes=bb_nodes,
            wall_time_s=time.perf_counter() - t0,
        )

    raise ValueError(f"unknown mode: {mode!r}")
