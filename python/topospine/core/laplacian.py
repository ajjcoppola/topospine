"""Real Hodge Laplacians, Betti numbers, and encoding-size counts.

Chains are over R with the usual oriented simplicial (or cubical) boundary.
``betti_real`` is the nullity of each combinatorial Hodge Laplacian
L_k = B_k^T B_k + B_{k+1} B_{k+1}^T.  This equals the real Betti number.
It is not the F2 Betti number when the integral homology has torsion
(RP^2 is the regression for that).

No quantum hardware and no quantum-advantage claim.  ``resource_counts`` is
only the dimension of the chain space: one qubit per cell, or the log of the
number of cells, and the Dirac operator on that space (its matrix is
square of that order).

Elementary collapse here removes a free face and its unique coface and keeps
every other face.  That is a simple-homotopy equivalence, so the Laplacian
kernel dimension is unchanged.  The positive spectrum is not claimed to be
invariant; ``spectral_gaps`` is reported so a change can be seen.
The stock ``ElementaryCubicalCollapsePass`` deletes a top cell outright and is
a different operation; it is not what these tests certify.
"""

from __future__ import annotations

import math
from typing import Sequence

from topospine.core.cubical import CubicalComplex
from topospine.core.cubes import BooleanCube, GridCube


def _betti_from_boundaries(boundaries: dict[int, "object"], tol: float = 1e-8) -> tuple[list[int], list[float | None]]:
    """``boundaries[k]`` is the real matrix of ∂_k, shape (number of (k-1)-cells, number of k-cells)."""
    import numpy as np

    if not boundaries:
        return [], []
    mats: dict[int, "object"] = {}
    ncells: dict[int, int] = {}
    for k, raw in boundaries.items():
        B = np.asarray(raw, dtype=float)
        if B.ndim != 2:
            raise ValueError("boundary matrix must be 2-d")
        mats[k] = B
        ncells[k] = int(B.shape[1])
        ncells[k - 1] = int(B.shape[0])
    ncells.pop(-1, None)
    # a zero column-count at the top (no k-cells) should not create an empty degree
    while ncells and ncells[max(ncells)] == 0:
        ncells.pop(max(ncells))
    if not ncells:
        return [], []
    betti: list[int] = []
    gaps: list[float | None] = []
    for k in range(max(ncells) + 1):
        n = ncells.get(k, 0)
        Bk = mats.get(k)
        if Bk is None or Bk.shape[1] != n:
            Bk = np.zeros((ncells.get(k - 1, 0), n))
        Bkp = mats.get(k + 1)
        if Bkp is None or Bkp.shape[0] != n:
            Bkp = np.zeros((n, ncells.get(k + 1, 0)))
        L = Bk.T @ Bk + Bkp @ Bkp.T
        if n == 0:
            betti.append(0)
            gaps.append(None)
            continue
        rank = int(np.sum(np.linalg.svd(L, compute_uv=False) > tol))
        betti.append(n - rank)
        ev = np.linalg.eigvalsh((L + L.T) / 2)
        pos = ev[ev > tol]
        gaps.append(float(pos.min()) if len(pos) else None)
    return betti, gaps


def simplicial_boundaries(facets: Sequence[Sequence[int]]) -> dict[int, "object"]:
    """Oriented boundary matrices of the simplicial complex generated by ``facets``."""
    import numpy as np
    from topospine.core.cohomology import skeleton

    cells = skeleton(facets)
    if not cells:
        return {}
    index = {d: {s: i for i, s in enumerate(cs)} for d, cs in cells.items()}
    out: dict[int, object] = {}
    for k in range(1, max(cells) + 1):
        rows, cols = len(cells[k - 1]), len(cells[k])
        B = np.zeros((rows, cols))
        for j, sigma in enumerate(cells[k]):
            for r, v in enumerate(sigma):
                face = sigma[:r] + sigma[r + 1 :]
                B[index[k - 1][face], j] += (-1) ** r
        out[k] = B
    if 0 in cells and 1 not in cells:
        out[1] = np.zeros((len(cells[0]), 0))
    return out


def simplicial_betti_real(facets: Sequence[Sequence[int]], tol: float = 1e-8) -> list[int]:
    betti, _gaps = _betti_from_boundaries(simplicial_boundaries(facets), tol)
    return betti


def simplicial_spectrum(facets: Sequence[Sequence[int]], tol: float = 1e-8) -> dict:
    betti, gaps = _betti_from_boundaries(simplicial_boundaries(facets), tol)
    return {"betti_real": betti, "spectral_gaps": gaps, "n_cells": _n_cells_simplicial(facets)}


def _n_cells_simplicial(facets: Sequence[Sequence[int]]) -> int:
    from topospine.core.cohomology import skeleton

    cells = skeleton(facets)
    return sum(len(v) for v in cells.values())


def resource_counts(n_cells: int) -> dict:
    """Chain-space dimensions.  Not a device, not a speedup."""
    if n_cells < 0:
        raise ValueError("n_cells")
    log_q = 0 if n_cells <= 1 else math.ceil(math.log2(n_cells))
    return {
        "cells": n_cells,
        "qubits_one_per_cell": n_cells,
        "qubits_log_encoding": log_q,
        "dirac_dimension": n_cells,
    }


def rp2() -> list[tuple[int, int, int]]:
    """Minimal 6-vertex triangulation of RP^2 (10 triangles, Euler characteristic 1)."""
    raw = [
        (0, 1, 2), (0, 2, 3), (0, 3, 4), (0, 4, 5), (0, 5, 1),
        (1, 2, 4), (2, 3, 5), (3, 4, 1), (4, 5, 2), (5, 1, 3),
    ]
    return [tuple(sorted(t)) for t in raw]  # type: ignore[misc]


def free_pair_simplicial(facets: Sequence[Sequence[int]]) -> tuple[tuple[int, ...], tuple[int, ...]] | None:
    """A simplex contained in exactly one coface one dimension up, and that coface."""
    from topospine.core.cohomology import skeleton

    cells = skeleton(facets)
    for d in sorted(cells, reverse=True):
        if d == 0:
            continue
        for face in cells[d - 1]:
            containers = [s for s in cells[d] if set(face) <= set(s)]
            if len(containers) == 1:
                return face, containers[0]
    return None


def collapse_simplicial_once(facets: Sequence[Sequence[int]]) -> list[tuple[int, ...]] | None:
    """Remove one free pair.  Remaining maximal faces are recomputed."""
    from topospine.core.cohomology import skeleton

    pair = free_pair_simplicial(facets)
    if pair is None:
        return None
    face, coface = pair
    cells = skeleton(facets)
    banned = {face, coface}
    kept = [s for d, ss in cells.items() for s in ss if s not in banned]
    # maximal among kept
    maximal = []
    for s in kept:
        if any(set(s) < set(t) for t in kept):
            continue
        maximal.append(s)
    return maximal


def _all_cubical_faces(cx: CubicalComplex) -> dict[str, BooleanCube | GridCube]:
    faces: dict[str, BooleanCube | GridCube] = {}

    def add(cell) -> None:
        key = str(cell)
        if key in faces:
            return
        faces[key] = cell
        for face in cell.faces():
            add(face)

    for cell in cx.top_cells:
        add(cell)
    return faces


def _cubical_sign_and_face(cell, axis_slot: int, endpoint: int):
    """Oriented codimension-1 face.

    ``axis_slot`` is the index among free axes (0 .. dim-1), not the ambient coordinate.
    ``endpoint`` 0 = lower, 1 = upper.  Sign is (-1)^slot * (1 if upper else -1).
    """
    sign = ((-1) ** axis_slot) * (1 if endpoint == 1 else -1)
    if isinstance(cell, BooleanCube):
        free = [i for i, b in enumerate(cell.bits) if b is None]
        coord = free[axis_slot]
        bits = list(cell.bits)
        bits[coord] = 0 if endpoint == 0 else 1
        return sign, BooleanCube(tuple(bits))
    free = [i for i, c in enumerate(cell.coords) if isinstance(c, tuple)]
    coord = free[axis_slot]
    lo, hi = cell.coords[coord]
    new = list(cell.coords)
    new[coord] = lo if endpoint == 0 else hi
    return sign, GridCube(tuple(new))


def cubical_boundaries(cx: CubicalComplex):
    import numpy as np

    faces = _all_cubical_faces(cx)
    if not faces:
        return {}
    by_dim: dict[int, list] = {}
    for cell in faces.values():
        by_dim.setdefault(cell.dimension, []).append(cell)
    for d in by_dim:
        by_dim[d] = sorted(by_dim[d], key=str)
    index = {d: {str(c): i for i, c in enumerate(cs)} for d, cs in by_dim.items()}
    out = {}
    max_d = max(by_dim)
    for k in range(1, max_d + 1):
        rows = len(by_dim.get(k - 1, []))
        cols = len(by_dim.get(k, []))
        B = np.zeros((rows, cols))
        for j, cell in enumerate(by_dim.get(k, [])):
            for slot in range(k):
                for end in (0, 1):
                    sign, face = _cubical_sign_and_face(cell, slot, end)
                    B[index[k - 1][str(face)], j] += sign
        out[k] = B
    return out


def cubical_betti_real(cx: CubicalComplex, tol: float = 1e-8) -> list[int]:
    betti, _gaps = _betti_from_boundaries(cubical_boundaries(cx), tol)
    return betti


def cubical_spectrum(cx: CubicalComplex, tol: float = 1e-8) -> dict:
    faces = _all_cubical_faces(cx)
    betti, gaps = _betti_from_boundaries(cubical_boundaries(cx), tol)
    return {"betti_real": betti, "spectral_gaps": gaps, "n_cells": len(faces)}


def pair_collapse_cubical(cx: CubicalComplex) -> CubicalComplex | None:
    """One elementary collapse: drop the free face and its unique top coface.

    Other faces of that coface stay in the complex (promoted to top cells when
    nothing else contains them).
    """
    coll = cx.collapsible_cells()
    if not coll:
        return None
    cell, faces = coll[0]
    face = faces[0]
    others = [c for c in cx.top_cells if c != cell]
    extra = []
    for f in cell.faces():
        if str(f) == str(face):
            continue
        if any(str(f) == str(o) or f.is_face_of(o) for o in others):
            continue
        extra.append(f)
    return CubicalComplex(top_cells=others + extra, name=cx.name)


def delete_one_top(cx: CubicalComplex, index: int = 0) -> CubicalComplex:
    """Delete a generating top cell and every face that belonged only to it.

    This is not an elementary collapse.  It is the random-deletion baseline.
    """
    if not cx.top_cells:
        return cx
    i = index % len(cx.top_cells)
    tops = [c for k, c in enumerate(cx.top_cells) if k != i]
    return CubicalComplex(top_cells=tops, name=cx.name)
